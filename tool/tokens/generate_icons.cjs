const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {assemble,output,root,json}=require('../figma/assemble_icons_snapshot.cjs');
function generate(check=false) {
  const {concepts,versions,buttonIcons}=assemble(true);
  const records=Object.fromEntries(concepts.map(c=>[c.key,{...c,artworks:Object.fromEntries(versions.filter(v=>v.logicalKey===c.key).map(v=>[v.style,v]))}]));
  const dartValue=x=>JSON.stringify(x).replace(/\$/g,'\\$');
  let code=`// GENERATED by tool/tokens/generate_icons.cjs. Do not edit.\n`+
    `enum AppIconId { ${concepts.map(c=>c.dartId).join(', ')} }\n`+
    `const appIconKeys = <AppIconId,String>{${concepts.map(c=>`AppIconId.${c.dartId}:${dartValue(c.key)}`).join(',')}};\n`+
    `const iconRegistryData = <String,Map<String,dynamic>>${dartValue(records)};\n`+
    `const buttonIconSourceKeys = <String,Map<String,String>>${dartValue(buttonIcons)};\n`;
  const temp=path.join(root,'build/icon-generation');fs.mkdirSync(temp,{recursive:true});
  const file=path.join(temp,'icon_registry.g.dart');fs.writeFileSync(file,code);
  execFileSync(process.env.DART||'D:/Tools/flutter/bin/cache/dart-sdk/bin/dart.exe',['format',file]);code=fs.readFileSync(file,'utf8');
  output('packages/design_system/lib/src/icons/generated/icon_registry.g.dart',code,check);
  const obsolete=path.join(root,'packages/design_system/lib/src/icons/generated/button_icons.g.dart');
  if(check) { if(fs.existsSync(obsolete))throw Error('Obsolete partial icon registry remains'); }
  else if(fs.existsSync(obsolete))fs.unlinkSync(obsolete);
  for(const v of versions)output(`packages/design_system/${v.assetPath}`,fs.readFileSync(path.join(root,'docs/snapshots/2026-10-20_development-icons',v.file)),check);
  const expected=new Set(versions.map(v=>v.assetPath));
  for(const style of ['fill','outline'])for(const f of fs.readdirSync(path.join(root,`packages/design_system/assets/icons/system/${style}`))) {
    if(!expected.has(`assets/icons/system/${style}/${f}`))throw Error('Unexpected runtime asset: '+f);
  }
  console.log(`${check?'Verified':'Generated'} ${versions.length} runtime assets and registry.`);
}
module.exports={generate};if(require.main===module)generate(process.argv.includes('--check'));
