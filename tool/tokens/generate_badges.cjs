const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'../..'),snap='docs/snapshots/2026-10-20_development-badges';
const check=process.argv.includes('--check');
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p)));
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
function output(p,s){const f=path.join(root,p);if(check){if(!fs.existsSync(f)||fs.readFileSync(f,'utf8')!==s)throw Error('Stale '+p);}else{fs.mkdirSync(path.dirname(f),{recursive:true});fs.writeFileSync(f,s);}}
const inventory=read(`${snap}/evidence/inventory.json`),foundations=read(`${snap}/evidence/foundations.json`);
const library=read('docs/snapshots/2026-10-20_development-icons/icons.json');
if(!inventory.complete||!foundations.complete||foundations.missing.length)throw Error('Incomplete Badge evidence');
const walk=n=>[n,...(n.children||[]).flatMap(walk)];
const rows=[];
for(const set of inventory.sets)for(const variant of set.variants){
 const evidence=read(`${snap}/evidence/variant-${variant.id.replace(':','-')}.json`);
 if(!evidence.complete||evidence.root.id!==variant.id)throw Error('Incomplete variant '+variant.id);
 const n=evidence.root,all=walk(n),text=all.find(c=>c.type==='TEXT'),label=n.children.find(c=>c.name==='Text Label');
 const slot=n.children.find(c=>c.name==='Icon (Optional)');
 const icons=Object.fromEntries(slot.children.map(i=>{
   const master=library.versions.find(v=>v.nodeId===i.mainComponent?.id);
   if(!master)throw Error('Unknown Badge icon '+i.id);
   const paint=walk(i).find(v=>v.fills?.some(p=>p.type==='SOLID'))?.fills;
   if(!paint)throw Error('Missing hidden/visible icon paint '+i.id);
   return [master.style,{...master,nodeId:master.nodeId,instanceId:i.id,visible:i.visible,paint}];
 }));
 rows.push({id:n.id,rawName:n.name,setId:set.id,setName:set.name,fileKey:inventory.fileKey,
  size:set.name.split(' ')[0].toLowerCase(),brightness:set.name.includes('Light')?'light':'dark',
  appearance:variant.props.Button==='Disable'?'disabled':variant.props.Button.toLowerCase(),
  sourceAxis:variant.props,body:Object.fromEntries(Object.entries(n).filter(([k])=>k!=='children')),
  text,labelFrame:Object.fromEntries(Object.entries(label).filter(([k])=>k!=='children')),
  iconSlot:Object.fromEntries(Object.entries(slot).filter(([k])=>k!=='children')),icons,
  reactions:all.flatMap(v=>(v.reactions||[]).map(r=>({nodeId:v.id,...r})))});
}
if(rows.length!==30||new Set(rows.map(r=>r.id)).size!==30)throw Error('Live Badge inventory changed; review source count');
const data={fileKey:inventory.fileKey,rows,foundations,sets:inventory.sets};
output(`${snap}/badges.json`,JSON.stringify(data,null,2)+'\n');
output(`${snap}/manifest.json`,JSON.stringify({status:'DEVELOPMENT',sourceAccess:'read-only MCP',fileKey:inventory.fileKey,page:inventory.page,versionId:null,designerApproval:null,counts:{sets:inventory.sets.length,variants:rows.length},evidenceHashes:Object.fromEntries(fs.readdirSync(path.join(root,snap,'evidence')).sort().map(f=>[f,hash(fs.readFileSync(path.join(root,snap,'evidence',f)))]))},null,2)+'\n');
const temp=path.join(root,'build/badge-generation/badge_data.g.dart');fs.mkdirSync(path.dirname(temp),{recursive:true});
fs.writeFileSync(temp,`// GENERATED by tool/tokens/generate_badges.cjs. Do not edit.\nconst badgeSourceData = <String,dynamic>${JSON.stringify(data).replace(/\$/g,'\\$')};\n`);
execFileSync(process.env.DART||'D:/Tools/flutter/bin/cache/dart-sdk/bin/dart.exe',['format',temp]);
output('packages/design_system/lib/src/tokens/generated/badge_data.g.dart',fs.readFileSync(temp,'utf8'));
console.log(`${check?'Verified':'Generated'} ${rows.length} Badge variants / ${inventory.sets.length} source sets; all icon links and hidden paints resolved.`);
